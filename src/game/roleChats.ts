const lastUsedIndex = new Map<string, number>();

export function findRoleChatReply(role: ChatRole, questionText: string): RoleChatReply {
  const q = questionText.trim().toLowerCase();
  const roleEntries = ROLE_CHAT_BANK.filter((e) => e.role === role);
  const meta = ROLE_META[role];

  if (!q) {
    const idx = Math.floor(Math.random() * roleEntries.length);
    const chosen = roleEntries[idx];
    return {
      text: chosen.text,
      emotion: chosen.emotion,
      role,
      speakerName: meta.speakerName,
      isFemaleVoice: meta.isFemaleVoice,
      totalBankCount: ROLE_CHAT_BANK.length,
    };
  }

  // Score every entry in this role by keyword match & word overlap
  let bestScore = -1;
  let candidates: RoleChatEntry[] = [];

  for (const entry of roleEntries) {
    let score = 0;
    for (const kw of entry.keywords) {
      if (q.includes(kw.toLowerCase())) {
        score += 10 + kw.length;
      }
    }
    const qTokens = q.split(/\s+/).filter((t) => t.length >= 2);
    for (const tok of qTokens) {
      if (entry.text.toLowerCase().includes(tok)) score += 3;
    }

    if (score > bestScore) {
      bestScore = score;
      candidates = [entry];
    } else if (score === bestScore && score > 0) {
      candidates.push(entry);
    }
  }

  const pool = bestScore > 0 ? candidates : roleEntries;
  const key = `${role}:${q.slice(0, 16)}`;
  const prevIdx = lastUsedIndex.get(key) ?? -1;
  const nextIdx = (prevIdx + 1) % pool.length;
  lastUsedIndex.set(key, nextIdx);

  const chosen = pool[nextIdx];
  return {
    text: chosen.text,
    emotion: chosen.emotion,
    role,
    speakerName: meta.speakerName,
    isFemaleVoice: meta.isFemaleVoice,
    totalBankCount: ROLE_CHAT_BANK.length,
  };
}
